class FakeSlicer:
    def __init__(self, in_progress_polls: int = 2, import_errors=None):
        self.commands = []
        self.progress_calls = 0
        # Number of progress polls to report "in progress" before reporting finished,
        # mimicking a real slice that flips all_plate_finished False->True.
        self.in_progress_polls = in_progress_polls
        self.import_errors = list(import_errors or [])
        self._since_trigger = 0

    def __call__(self, command, params_json, recvcmd_timeout=None, band_output=False):
        self.commands.append(command)
        params = json.loads(params_json) if params_json else {}
        if command == "get_slicing_progress":
            self.progress_calls += 1
            self._since_trigger += 1
            finished = self._since_trigger > self.in_progress_polls
            # Match the real engine snapshot: while slicing the notification
            # reports state="progress" with all_plate_finished=False; once the
            # slice finishes the transient SP_COMPLETED resets to SP_NO_SLICING
            # almost immediately, so polling observes state="no_slicing" with
            # all_plate_finished=True (on-disk result ready). We never emit
            # "completed" here on purpose: the real engine's "completed" window
            # is too short to catch, and the flow must not depend on it.
            payload = {
                "code": 0,
                "payload": {
                    "all_plate_finished": finished,
                    "progress": {
                        "percentage": 100 if finished else 50,
                        "state": "no_slicing" if finished else "progress",
                    },
                },
            }
        elif command == "trigger_slice":
            # A new slice starts: reset so progress reports in-progress first.
            self._since_trigger = 0
            payload = {"code": 0, "payload": {}}
        elif command == "get_error":
            payload = {"code": 0, "payload": {"data": self.import_errors}}
        elif command == "export_gcode":
            with zipfile.ZipFile(params["output"], "w") as zf:
                zf.writestr("case.gcode", "; generated by fake slicer\n")
            payload = {"code": 0, "payload": {}}
        else:
            payload = {"code": 0, "payload": {}}
        return True, "ok", f"{command}_respone;{json.dumps(payload)}".encode("utf-8")


class FakeCommandInjector:
    def __init__(self, future: Future, process_state):
        self.future = future
        self._process_state = process_state

    def submit(self, *_args, **_kwargs):
        return self.future

    def process_state(self):
        return dict(self._process_state)


class TimeoutFuture(Future):
    def result(self, timeout=None):
        raise FutureTimeoutError()


def test_future_timeout_is_not_reported_as_crash_while_process_is_running():
    injector = FakeCommandInjector(
        TimeoutFuture(),
        {"running": True, "pid": 1234, "returncode": None},
    )

    def send_cmd(command, params_json, recvcmd_timeout=None, band_output=False):
        return _send_engine_command(injector, command, params_json, recvcmd_timeout, band_output)

    result = _run_command(send_cmd, "trigger_load_project2", {"file": "case.3mf"}, timeout=90)

    assert result["ok"] is False
    assert result["status"] == "timeout"
    assert result["crashed"] is False
    assert "TimeoutError" in result["error"]
    assert "process=running" in result["error"]
    assert "pid=1234" in result["error"]


def test_future_timeout_is_reported_as_lost_connection_after_process_exit():
    injector = FakeCommandInjector(
        TimeoutFuture(),
        {"running": False, "pid": 5678, "returncode": -1073741819},
    )

    def send_cmd(command, params_json, recvcmd_timeout=None, band_output=False):
        return _send_engine_command(injector, command, params_json, recvcmd_timeout, band_output)

    result = _run_command(send_cmd, "get_slicing_progress", {}, timeout=60)

    assert result["ok"] is False
    assert result["status"] == "lostconnect"
    assert result["crashed"] is True
    assert "process=exited" in result["error"]
    assert "returncode=-1073741819" in result["error"]


