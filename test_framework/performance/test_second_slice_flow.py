def test_is_slicing_done_uses_state_completed():
    # The reliable completion signal is the live state machine ("completed"),
    # which the engine sets exactly when a slice finishes.
    assert _is_slicing_done({"state": "completed", "all_plate_finished": False}) is True
    assert _is_slicing_done({"state": "completed", "all_plate_finished": True}) is True


def test_is_slicing_done_real_engine_no_slicing_after_finish():
    # The real engine resets its SlicingProgressNotification to SP_NO_SLICING
    # shortly after a slice completes (the transient "completed" state is rarely
    # caught by polling). At that point state="no_slicing" but the on-disk result
    # is ready, so all_plate_finished=True. This stable post-slice idle state
    # must count as done, otherwise the wait dead-ends into the 120s stall guard.
    assert _is_slicing_done({"state": "no_slicing", "all_plate_finished": True}) is True


def test_is_slicing_done_no_slicing_without_result_is_not_done():
    # state="no_slicing" with no ready result means slicing has not produced
    # anything yet (e.g. before the slice actually starts) -> not done.
    assert _is_slicing_done({"state": "no_slicing", "all_plate_finished": False}) is False


def test_is_slicing_done_re_slice_in_progress_not_done_even_if_old_result_ready():
    # Re-slice: on-disk result from the previous slice stays ready (all_plate_finished
    # is True the whole time), but the live state is "progress" => NOT done yet.
    # This is the case that previously caused stale-flag short-circuit / deadlock.
    assert _is_slicing_done({"state": "progress", "all_plate_finished": True}) is False


def test_is_slicing_done_falls_back_to_all_plate_finished_without_state():
    # Engines that do not report state fall back to all_plate_finished.
    assert _is_slicing_done({"all_plate_finished": True}) is True
    assert _is_slicing_done({"all_plate_finished": False}) is False


def test_idle_no_slicing_retry_match_is_exact():
    assert _is_idle_no_slicing_progress({"percentage": -1, "state": "no_slicing"}) is True
    assert _is_idle_no_slicing_progress({"percentage": 71, "state": "progress"}) is False
    assert _is_idle_no_slicing_progress({"percentage": -1, "state": "progress"}) is False
    assert _is_idle_no_slicing_progress({"percentage": 0, "state": "no_slicing"}) is False


class FakeEngineManager:
    def __init__(self):
        self.restart_calls = 0

    def restart(self):
        self.restart_calls += 1


def test_run_slice_flow_retries_idle_no_slicing_once(tmp_path: Path, monkeypatch):
    attempts = []
    results = [
        {
            "export_ok": False,
            "retryable_idle_no_slicing": True,
            "error": "percentage=-1.000, state=no_slicing",
        },
        {"export_ok": True, "retryable_idle_no_slicing": False, "error": None},
    ]

    def fake_run_slice_flow(*args):
        attempts.append(args)
        return results[len(attempts) - 1]

    monkeypatch.setenv("SLICER_IDLE_NO_SLICING_RETRIES", "1")
    monkeypatch.setattr(slice_case, "_run_slice_flow", fake_run_slice_flow)
    manager = FakeEngineManager()

    result = _run_slice_flow_with_idle_retry(object(), manager, tmp_path / "case.3mf", tmp_path)

    assert result["export_ok"] is True
    assert result["idle_no_slicing_retries"] == 1
    assert len(attempts) == 2
    assert manager.restart_calls == 1


