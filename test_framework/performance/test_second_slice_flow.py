import json
import zipfile
from pathlib import Path

from test_framework.performance.case.test_slice import _run_slice_flow, _is_slicing_done


class FakeSlicer:
    def __init__(self, in_progress_polls: int = 2):
        self.commands = []
        self.progress_calls = 0
        # Number of progress polls to report "in progress" before reporting finished,
        # mimicking a real slice that flips all_plate_finished False->True.
        self.in_progress_polls = in_progress_polls
        self._since_trigger = 0

    def __call__(self, command, params_json, recvcmd_timeout=None, band_output=False):
        self.commands.append(command)
        params = json.loads(params_json) if params_json else {}
        if command == "get_slicing_progress":
            self.progress_calls += 1
            self._since_trigger += 1
            finished = self._since_trigger > self.in_progress_polls
            # Match the real engine snapshot: while slicing the notification
            # reports state="progress" with all_plate_finished=False; once the
            # slice finishes the transient SP_COMPLETED resets to SP_NO_SLICING
            # almost immediately, so polling observes state="no_slicing" with
            # all_plate_finished=True (on-disk result ready). We never emit
            # "completed" here on purpose: the real engine's "completed" window
            # is too short to catch, and the flow must not depend on it.
            payload = {
                "code": 0,
                "payload": {
                    "all_plate_finished": finished,
                    "progress": {
                        "percentage": 100 if finished else 50,
                        "state": "no_slicing" if finished else "progress",
                    },
                },
            }
        elif command == "trigger_slice":
            # A new slice starts: reset so progress reports in-progress first.
            self._since_trigger = 0
            payload = {"code": 0, "payload": {}}
        elif command == "get_error":
            payload = {"code": 0, "payload": {"data": []}}
        elif command == "export_gcode":
            with zipfile.ZipFile(params["output"], "w") as zf:
                zf.writestr("case.gcode", "; generated by fake slicer\n")
            payload = {"code": 0, "payload": {}}
        else:
            payload = {"code": 0, "payload": {}}
        return True, "ok", f"{command}_respone;{json.dumps(payload)}".encode("utf-8")


def test_run_slice_flow_slices_then_moves_model_then_slices_again(tmp_path: Path, monkeypatch):
    monkeypatch.setenv("ENABLE_SECOND_SLICE", "true")
    monkeypatch.setenv("SLICER_PROGRESS_POLL", "0.001")
    model_path = tmp_path / "case.3mf"
    model_path.write_bytes(b"fake 3mf")
    slicer = FakeSlicer()

    result = _run_slice_flow(slicer, model_path, tmp_path)

    assert result["import_ok"] is True
    assert result["move_ok"] is True
    assert result["slice_ok"] is True
    assert result["first_slice_ms"] is not None
    assert result["second_slice_ms"] is not None
    assert result["slice_ms"] == result["second_slice_ms"]
    # second slice: one moved-model slice by default (first + second = one test group)
    assert result["second_slice_trials"]
    assert len(result["second_slice_trials"]) == 1
    expected_mean = round(sum(result["second_slice_trials"]) / len(result["second_slice_trials"]), 2)
    assert result["second_slice_ms"] == expected_mean
    # 1 first slice + 1 second slice = 2 trigger_slice calls
    assert slicer.commands.count("trigger_slice") == 2
    assert slicer.commands.count("move_model_instance") == 1
    assert slicer.commands.index("move_model_instance") > slicer.commands.index("trigger_slice")
    assert slicer.commands.index("move_model_instance") < len(slicer.commands) - 1


